test('M3B fingerprints bind applicability values to geometry and declaration evidence only to content', async () => {
  const doc = document(); const requested = selected(doc);
  const initial = await evaluateQuantities(doc, requested); assert.ok(initial.ok);
  assert.equal(initial.evaluation.fingerprints.geometryScope, 'physical-geometry-v2');
  const evidence = structuredClone(doc); evidence.calculationContract!.rooms['room-1'].ceiling.detail = 'Inspected finished ceiling';
  const next = await evaluateQuantities(evidence, requested); assert.ok(next.ok);
  assert.equal(next.evaluation.fingerprints.geometry, initial.evaluation.fingerprints.geometry);
  assert.notEqual(next.evaluation.fingerprints.content, initial.evaluation.fingerprints.content);
  evidence.calculationContract!.rooms['room-1'].ceiling = createUnknownRoomApplicability().ceiling;
  const changed = await evaluateQuantities(evidence, requested); assert.ok(changed.ok);
  assert.notEqual(changed.evaluation.fingerprints.geometry, initial.evaluation.fingerprints.geometry);
  const view = structuredClone(doc); view.name = 'Renamed'; view.viewport = { scale: 2, panX: 300 };
  view.rooms[0].presentation!.color = 'red'; view.editorContract = { version: 'sketch-editor-v1', groups: [{ id: 'group-a', roomIds: ['room-1'] }] };
  const presentation = await evaluateQuantities(view, requested); assert.ok(presentation.ok);
  assert.deepEqual(presentation.evaluation.fingerprints, initial.evaluation.fingerprints);
});

test('M3B v2 snapshot confirmation gate, version agreement and independent integrity verification', async () => {
  const doc = document(); const requested = selected(doc);
  const captured = await createQuantitySnapshot(doc, requested, metadata()); assert.ok(captured.ok);
  assert.equal(captured.snapshot.snapshotSchemaVersion, 'quantity-snapshot-v2');
  assert.deepEqual(await verifyQuantitySnapshot(captured.snapshot), { ok: true });
  const mixed = structuredClone(captured.snapshot); mixed.snapshotSchemaVersion = 'quantity-snapshot-v1';
  assert.equal(quantitySnapshotSchema.safeParse(mixed).success, false);
  const changed = structuredClone(captured.snapshot); changed.sourceDocument.calculationContract!.rooms['room-1'].ceiling.detail = 'different source evidence';
  assert.equal((await verifyQuantitySnapshot(changed)).ok, false);
  for (const incomplete of [document(false), document()]) {
    if (incomplete.calculationContract!.rooms['room-1'].ceiling.confirmation.status === 'confirmed') {
      incomplete.calculationContract!.rooms['room-1'] = createUnknownRoomApplicability();
    }
    assert.equal((await createQuantitySnapshot(incomplete, selected(incomplete), metadata())).ok, false);
    assert.equal((await createQuantitySnapshot(incomplete, selected(incomplete), metadata('evaluation'))).ok, true);
    assert.equal((await createQuantitySnapshot(incomplete, selected(incomplete, [{ output: 'floor-area', roomIds: ['room-1'], wasteFraction: 0 }]), metadata())).ok, true);
  }
});


