function document(confirmed = true): PhysicalDocument {
  const doc = q001();
  doc.quantityPolicyVersion = QUANTITY_POLICY_VERSION_V2;
  const profile = createProposedRoomApplicability();
  if (confirmed) for (const field of APPLICABILITY_FIELDS) profile[field].confirmation = { status: 'confirmed', confirmedAt: AT };
  doc.calculationContract = { version: 'room-applicability-v1', rooms: { 'room-1': profile } };
  return doc;
}
function selected(doc: PhysicalDocument, selections = allSelections(doc)): QuantityRequest {
  return { ...request(selections), policy: { version: QUANTITY_POLICY_VERSION_V2, openingMeasureBasis: 'finished', crownFullHeightGaps: [] } };
}
function calculation(doc: PhysicalDocument, requested = selected(doc)) {
  const result = calculateQuantities(doc, requested);
  assert.ok(result.ok, JSON.stringify(result));
  return result.calculation;
}
const squareFeet = (mm2: number) => mm2 / (304.8 * 304.8);
const output = (doc: PhysicalDocument, id: string, requested = selected(doc)) => calculation(doc, requested).outputs.find(value => value.output === id)!;
const metadata = (kind: 'evaluation' | 'confirmed' = 'confirmed') => ({ id: 'm3b-capture', createdAt: AT, kind });

