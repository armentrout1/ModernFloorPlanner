test('M3B applicability and group contracts validate exact room ownership without inferring topology', () => {
  const doc = document(); doc.rooms.push(room('room-2'));
  doc.calculationContract!.rooms['room-2'] = createProposedRoomApplicability();
  doc.editorContract = { version: 'sketch-editor-v1', groups: [{ id: 'group-a', roomIds: ['room-1', 'room-2'] }] };
  assert.ok(physicalDocumentSchema.safeParse(doc).success);
  for (const mutate of [
    (d: PhysicalDocument) => { delete d.calculationContract!.rooms['room-2']; },
    (d: PhysicalDocument) => { d.calculationContract!.rooms.ghost = createProposedRoomApplicability(); },
    (d: PhysicalDocument) => { d.editorContract!.groups[0].roomIds.push('room-1'); },
    (d: PhysicalDocument) => { d.editorContract!.groups.push({ id: 'group-b', roomIds: ['room-1'] }); },
    (d: PhysicalDocument) => { d.editorContract!.groups[0].roomIds.push('ghost'); },
    (d: PhysicalDocument) => { d.editorContract!.groups.push({ id: 'group-a', roomIds: [] }); },
  ]) { const changed = structuredClone(doc); mutate(changed); assert.equal(physicalDocumentSchema.safeParse(changed).success, false); }
  for (const malformed of [null, [], new Date(), 'flat']) {
    const changed = structuredClone(doc) as any; changed.calculationContract.rooms = malformed;
    assert.equal(physicalDocumentSchema.safeParse(changed).success, false);
  }
  const unknown = createUnknownRoomApplicability();
  assert.equal(roomApplicabilitySchema.safeParse({ ...unknown, ceiling: { ...unknown.ceiling, detail: ' ' } }).success, false);
  assert.equal(roomApplicabilitySchema.safeParse({ ...unknown, ceiling: { ...unknown.ceiling, confirmation: { status: 'confirmed', confirmedAt: AT } } }).success, false);
});

