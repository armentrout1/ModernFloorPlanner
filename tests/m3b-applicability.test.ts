test('M3B policy dispatch rejects missing, mismatched and downgrade attempts without source rewrites', () => {
  const doc = document(), before = canonicalJson(doc);
  const downgrade = calculateQuantities(doc, request(allSelections(doc))); assert.equal(downgrade.ok, false);
  const missing = structuredClone(doc); delete missing.calculationContract;
  assert.equal(calculateQuantities(missing, selected(doc)).ok, false);
  const undeclared = structuredClone(doc); undeclared.quantityPolicyVersion = null;
  assert.equal(calculateQuantities(undeclared, selected(doc)).ok, false);
  const wrong = selected(doc); (wrong.policy as any).version = 'rectangular-flat-v99';
  assert.equal(calculateQuantities(doc, wrong).ok, false);
  assert.equal(canonicalJson(doc), before);
  const computed = structuredClone(calculation(doc));
  assert.equal(computed.schemaVersion, 'quantity-result-v2'); assert.equal(computed.engineVersion, 'rectangular-engine-v2');
  computed.schemaVersion = 'quantity-result-v1'; assert.equal(calculationSchema.safeParse(computed).success, false);
});

