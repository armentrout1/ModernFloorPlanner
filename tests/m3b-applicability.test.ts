test('M3B exact 12 by 10 ceiling-height acceptance keeps independent 120 square-foot surfaces', () => {
  const doc = document(); doc.openings = [];
  const work: QuantitySelection[] = [
    { output: 'floor-area', roomIds: ['room-1'], wasteFraction: 0 },
    { output: 'ceiling-area', roomIds: ['room-1'], wasteFraction: 0 },
    { output: 'gross-wall-area', wallFaceIds: doc.rooms[0].wallFaces.map(face => face.id), wasteFraction: 0 },
  ];
  const requested = selected(doc, work);
  for (const [height, wallArea] of [['8 ft', 352], ['9 ft', 396], ['2.7432 m', 396], ['8 ft 6 1/2 in', 44 * (8 + 6.5 / 12)]] as const) {
    doc.rooms[0].ceilingHeight = measured(height);
    assert.equal(squareFeet(output(doc, 'floor-area', requested).total!.net), 120);
    assert.equal(squareFeet(output(doc, 'ceiling-area', requested).total!.net), 120);
    assert.ok(Math.abs(squareFeet(output(doc, 'gross-wall-area', requested).total!.net) - wallArea) < 1e-10);
  }
  doc.rooms[0].ceilingHeight = unknownMeasurement('Height cleared');
  assert.equal(squareFeet(output(doc, 'floor-area', requested).total!.net), 120);
  assert.equal(squareFeet(output(doc, 'ceiling-area', requested).total!.net), 120);
  assert.equal(output(doc, 'gross-wall-area', requested).total, null);
  assert.equal(output(doc, 'gross-wall-area', requested).status, 'blocked');
});

